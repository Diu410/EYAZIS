def main():
    initialize()
    existing = {doc["title"] for doc in list_documents()}
    for title, body in SAMPLES:
        if title not in existing:
            add_document(title, body)
    for item in sample_files():
        if item["language"] != "ru" or item["title"] in existing:
            continue
        html = (ROOT / item["file"]).read_text(encoding="utf-8")
        _, body = extract_html(html)
        add_document(item["title"], body, item["url"])
    print(f"Коллекция содержит {len(list_documents())} документов.")


if __name__ == "__main__":
    main()
